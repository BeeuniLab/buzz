import { compileMessage } from '@lingui/message-utils/compileMessage';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const sourceModuleUrl = pathToFileURL(resolve(rootDir, 'src/i18n/catalogs.ts')).href;
const outputPath = resolve(rootDir, 'src/i18n/compiled-catalogs.ts');

const { DEFAULT_LOCALE, SUPPORTED_LOCALES, sourceMessages } = await import(sourceModuleUrl);

function compileCatalog(catalog) {
	const compiled = {};

	for (const [id, message] of Object.entries(catalog)) {
		compiled[id] = typeof message === 'string' ? compileMessage(message) : message;
	}

	return compiled;
}

const sourceIds = new Set();
for (const catalog of Object.values(sourceMessages)) {
	for (const id of Object.keys(catalog ?? {})) {
		sourceIds.add(id);
	}
}

const compiledMessages = Object.fromEntries(
	SUPPORTED_LOCALES.map((locale) => {
		if (locale === DEFAULT_LOCALE) {
			const defaultCatalog = Object.fromEntries([...sourceIds].map((id) => [id, id]));
			return [locale, compileCatalog(defaultCatalog)];
		}

		return [locale, compileCatalog(sourceMessages[locale] ?? {})];
	}),
);

const fileContents = `/* eslint-disable */
// This file is generated by scripts/compile-i18n-catalogs.mjs.
// Edit src/i18n/catalogs.ts, then run npm run i18n:compile.

import type { Messages } from '@lingui/core';
import type { AppLocale } from './catalogs';

export const compiledMessages: Record<AppLocale, Messages> = ${JSON.stringify(compiledMessages, null, '\t')};

export const compiledDefaultLocale = ${JSON.stringify(DEFAULT_LOCALE)} as AppLocale;
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, fileContents);

console.log(`Compiled ${SUPPORTED_LOCALES.length} i18n catalogs to ${outputPath}`);
